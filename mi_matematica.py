def es_par(numero):
    par = numero % 2 == 0
    return par

def el_doble(numero):
    doble = numero * 2
    return doble


def promedio(lista_numeros):
    prom = sum(lista_numeros) / len(lista_numeros)
    return prom

def area_circulo(radio):
    pi = 3.14159
    area = pi * radio ** 2
    return area

def mayor_que(numero1, numero2):
    ok = numero1 > numero2
    return ok

def suma(num1,num2,num3):
    suma = num1 + num2 + num3
    return suma
    
